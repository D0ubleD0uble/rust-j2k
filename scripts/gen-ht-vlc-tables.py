#!/usr/bin/env python3
"""Generate the HTJ2K CxtVLC tables for src/tier1/ht/vlc_tables.rs.

This is a developer tool. It is NOT run at `cargo test` time: the emitted file
is committed, and a unit test pins its checksum (`FNV-1a 64` over every row,
`CHECKSUM` below), so an edit by hand fails the suite.

The tables come from the text of the standard, never from another decoder:
Rec. ITU-T T.814 (06/2019) | ISO/IEC 15444-15:2019, Annex C, which prints
`CxtVLC_table_0` and `CxtVLC_table_1` as brace lists of 7-tuples
`{c_q, rho_q, u_off, eps_k, eps_1, w, l_w}`. The Recommendation is a free
download from the ITU:

    https://www.itu.int/rec/T-REC-T.814-201906-I/en

The script reads the PDF with `pdftotext -layout` (poppler-utils), takes the
text between `CxtVLC_table_N = {` and the closing `}}` of each table, and keeps
every `{...}` tuple in it, skipping the page headers and footers that fall
inside. It checks each row (field ranges, codeword fits its length, the codes
of each context are prefix-free) before writing anything.

The U-VLC code (T.814 7.3.6) is a procedure, not a table, so the decoder
implements it directly and nothing is generated for it.

Usage:
    scripts/gen-ht-vlc-tables.py T-REC-T.814-201906.pdf
    scripts/gen-ht-vlc-tables.py T-REC-T.814-201906.pdf -o -   # stdout
"""

from __future__ import annotations

import argparse
import hashlib
import re
import shutil
import subprocess
import sys
from pathlib import Path

# The SHA-256 of the PDF this file was generated from. Another printing of the
# Recommendation may lay the text out differently; pass --any-pdf to accept it.
PDF_SHA256 = "3480bb5f636d9a0bd654ecd31d6c756c0ec5667fe767acfb2b6771de9ddc3542"

# FNV-1a 64 over the rows, as `checksum()` computes it and the Rust test does.
CHECKSUM = 0x6087F93313D593F0

TUPLE = re.compile(r"\{\s*(\d+)\s*,\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*,"
                   r"\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*,"
                   r"\s*(\d+)\s*\}")


def table_text(text: str, name: str) -> str:
    start = text.index(f"{name} = {{")
    end = text.index("}}", start)
    return text[start + len(name) + 3 : end + 1]


def parse(text: str, name: str) -> list[tuple[int, ...]]:
    rows = [tuple(int(v, 0) for v in m.groups()) for m in TUPLE.finditer(table_text(text, name))]
    if not rows:
        sys.exit(f"{name}: no rows found")
    for row in rows:
        c, rho, u_off, e_k, e_1, w, l_w = row
        ok = (
            c < 8
            and rho < 16
            and u_off < 2
            and e_k < 16
            and e_1 < 16
            and 1 <= l_w <= 7
            and w < (1 << l_w)
            and e_1 & ~e_k == 0
            and e_k & ~rho == 0
            and (u_off == 1 or e_k == 0)
        )
        if not ok:
            sys.exit(f"{name}: row {row} is out of range")
    # Prefix-free within each context: no codeword is a (little-endian) prefix
    # of another, so decodeCxtVLC's first match is the only match.
    for c in range(8):
        codes = [(w, l) for (cq, _, _, _, _, w, l) in rows if cq == c]
        for i, (w1, l1) in enumerate(codes):
            for j, (w2, l2) in enumerate(codes):
                if i != j and l1 <= l2 and w2 & ((1 << l1) - 1) == w1:
                    sys.exit(f"{name}: context {c} codes {w1:#x}/{l1} and {w2:#x}/{l2} collide")
    return rows


def checksum(tables: list[list[tuple[int, ...]]]) -> int:
    h = 0xCBF29CE484222325
    for rows in tables:
        for row in rows:
            for v in row:
                h ^= v
                h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def emit(t0: list[tuple[int, ...]], t1: list[tuple[int, ...]]) -> str:
    out = [
        "// @generated by scripts/gen-ht-vlc-tables.py — do not edit by hand.",
        "//",
        "// The CxtVLC tables of Rec. ITU-T T.814 (06/2019) | ISO/IEC 15444-15:2019,",
        "// Annex C, transcribed from the text of the Recommendation. Each row is",
        "// `[c_q, rho_q, u_off, eps_k, eps_1, w, l_w]`: the context, the significance",
        "// pattern, the unsigned residual offset, the EMB known and known-1 patterns,",
        "// and the codeword `w` (little-endian, first bit in the LSB) of `l_w` bits.",
        "",
        "/// `CxtVLC_table_0`, for the quads of a code-block's first line-pair.",
        f"pub(super) const CXT_VLC_TABLE_0: [[u8; 7]; {len(t0)}] = [",
    ]
    fmt = "    [{}, 0x{:X}, {}, 0x{:X}, 0x{:X}, 0x{:02X}, {}],"
    out += [fmt.format(*r) for r in t0]
    out += [
        "];",
        "",
        "/// `CxtVLC_table_1`, for the quads of every later line-pair.",
        f"pub(super) const CXT_VLC_TABLE_1: [[u8; 7]; {len(t1)}] = [",
    ]
    out += [fmt.format(*r) for r in t1]
    out += ["];", ""]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("pdf", type=Path, help="the T.814 (06/2019) PDF")
    ap.add_argument("-o", "--output", default="src/tier1/ht/vlc_tables.rs",
                    help="output path, or - for stdout (default: src/tier1/ht/vlc_tables.rs)")
    ap.add_argument("--any-pdf", action="store_true",
                    help="accept a PDF whose SHA-256 differs from the pinned one")
    args = ap.parse_args()

    digest = hashlib.sha256(args.pdf.read_bytes()).hexdigest()
    if digest != PDF_SHA256 and not args.any_pdf:
        sys.exit(f"{args.pdf}: SHA-256 {digest} is not the pinned {PDF_SHA256} (see --any-pdf)")
    if shutil.which("pdftotext") is None:
        sys.exit("pdftotext (poppler-utils) is required")
    text = subprocess.run(["pdftotext", "-layout", str(args.pdf), "-"],
                          check=True, capture_output=True, text=True).stdout

    t0 = parse(text, "CxtVLC_table_0")
    t1 = parse(text, "CxtVLC_table_1")
    got = checksum([t0, t1])
    if got != CHECKSUM:
        print(f"note: checksum {got:#018X} differs from the pinned {CHECKSUM:#018X}; "
              "update CHECKSUM here and in src/tier1/ht/tests.rs if the text is right",
              file=sys.stderr)
    rust = emit(t0, t1)
    if args.output == "-":
        sys.stdout.write(rust)
    else:
        Path(args.output).write_text(rust)
        print(f"wrote {args.output}: {len(t0)} + {len(t1)} rows, checksum {got:#018X}", file=sys.stderr)


if __name__ == "__main__":
    main()
